/* ══ build-apis.ts — turn the public-apis catalog into src/data/freeApis.ts
   Source: https://github.com/public-apis/public-apis (README tables).
   Rows keep name, description, link, category, auth, HTTPS and CORS
   exactly as published; entries without a real description are dropped.
   Run: npx tsx scripts/build-apis.ts                                 ═ */
import { writeFileSync } from "fs";

type Row = { name: string; desc: string; link: string; cat: string; auth: string; https: boolean; cors: boolean };

const CAT_FIX: Record<string, string> = {
  "Animal": "Animals", "Anime": "Animals", "Anti-Malware": "Security", "Banking": "Finance",
  "Book": "Books", "Business": "Commerce", "Color": "Design", "Comic": "Entertainment",
  "Cryptocurrency": "Finance", "Currency Exchange Service": "Data", "Currency Exchange": "Finance",
  "Currency": "Finance", "Definition": "Text", "Development": "Developer", "Disaster": "Data",
  "Documentation": "Developer", "Email": "Messaging", "Feeds": "Data", "Gaming": "Entertainment",
  "Geographic": "Mapping and Geospatial", "Government": "Data", "Health": "Science and Math",
  "Identicon generation": "Design", "Logistics": "Data", "Machine Learning": "Science and Math",
  "Music": "Entertainment", "Navigation": "Mapping and Geospatial", "Password": "Security",
  "Personality": "Text", "Photography": "Design", "Privacy": "Security", "Product": "Commerce",
  "Productivity": "Developer", "Real Estate": "Data", "Retro": "Entertainment",
  "Screen Text Readers": "Developer", "Search: Environment": "Data", "Shading": "Design",
  "Social": "Messaging", "Sports": "Entertainment", "Test": "Developer", "Text": "Developer",
  "Trading": "Finance", "Transportation": "Data", "URL Shortening": "Developer",
  "University": "Data", "Weather & Geolocation": "Weather", "Weather": "Weather",
  "Web": "Developer", "Websites": "Entertainment", "Jobs": "Data",
};

const clean = (s: string) => s.replace(/\[?\s*\(?https?:\/\/www\.open\-apis\.com\/api\/#.*?\)?\s*\]?\s*/g, "").trim();

/* markdown link: [name](http://x) or plain name with URL later */
function parseLink(cell: string): { name: string; url: string } {
  const m = cell.match(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/);
  if (m) return { name: m[1].trim(), url: m[2].trim() };
  const u = cell.match(/https?:\/\/[^\s|)]+/);
  return { name: clean(cell).replace(/\*\*/g, "") || (u ? new URL(u[0]).hostname : ""), url: u?.[0] ?? "" };
}

async function main() {
  const r = await fetch("https://raw.githubusercontent.com/public-apis/public-apis/master/README.md");
  if (!r.ok) throw new Error(`fetch failed: HTTP ${r.status}`);
  const md = await r.text();

  const rows: Row[] = [];
  const seen = new Set<string>();
  let cat = "";
  for (const line of md.split("\n")) {
    const h3 = line.match(/^#{2,4}\s+(?:\d+\.\s+)?(?:\[)?([A-Za-z][^\]|]+)(?:\|[^\]]*)?\](?:\(#\w+\))?$/);
    const h3b = line.match(/^#{2,4}\s+([A-Za-z][\w .&+-]*)$/);
    if (line.startsWith("###")) {
      const name = (h3?.[1] ?? h3b?.[1] ?? "").trim();
      if (name && !/^(Contents|APIs)/i.test(name)) cat = name;
      continue;
    }
    if (!line.startsWith("|")) continue;
    const cells = line.split("|").map((c) => c.trim()).filter((c, i) => i > 0 && i < 6);
    if (cells.length < 5 || /---|^API$/i.test(cells.join(""))) continue;
    const [apiCell, descCell, authCell, httpsCell, corsCell] = cells;
    const { name, url } = parseLink(apiCell);
    const desc = clean(descCell);
    if (!name || !desc || !url || !cat) continue;
    const key = (name + url).toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    const rawAuth = authCell.replace(/\*\*/g, "").replace(/\[\s*\(?x?\)?\s*\]/gi, "").trim();
    const auth = /^no$/i.test(rawAuth.replace(/^\?$/, "No")) || rawAuth === "" || /^(no|none|optional)$/i.test(rawAuth) ? "no"
      : /oauth/i.test(rawAuth) ? "oauth" : "apiKey";
    rows.push({
      name: name.slice(0, 60), desc: desc.slice(0, 160), link: url,
      cat: CAT_FIX[cat] ?? cat,
      auth, https: /^yes$/i.test(httpsCell), cors: /^yes$/i.test(corsCell),
    });
  }

  /* keep it a directory of what you can actually call from a browser */
  const out = rows.filter((x) => x.https).sort((a, b) => a.cat.localeCompare(b.cat) || a.name.localeCompare(b.name));
  const cats = [...new Set(out.map((x) => x.cat))];

  const ts = `/* ══ freeApis.ts — the free API directory ═══════════════════════════════
   Generated by scripts/build-apis.ts from the public-apis catalog
   (github.com/public-apis/public-apis, community-maintained).
   ${out.length} endpoints across ${cats.length} categories. Regenerate, don't hand-edit. ══ */
export interface FreeApi { name: string; desc: string; link: string; cat: string; auth: "no" | "oauth" | "apiKey"; https: boolean; cors: boolean }
export const FREE_APIS: FreeApi[] = ${JSON.stringify(out, null, 0).replace(/\},/g, "},\n  ").replace(/^\[/, "[\n  ").replace(/\]$/, "\n]")};
export const API_CATEGORIES: string[] = ${JSON.stringify(cats)};
`;
  writeFileSync("src/data/freeApis.ts", ts.replace(/,\n]/g, "\n]"));
  console.log(`freeApis.ts: ${out.length} APIs, ${cats.length} categories`);
}

void main();
